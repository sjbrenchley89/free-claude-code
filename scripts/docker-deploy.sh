#!/bin/sh
set -eu

# Container deployment helper for Free Claude Code.
#
# Subcommands:
#   setup    Interactively write ./.env (provider, API key, model, proxy auth)
#   build    Build the Docker image
#   start    Start the stack in the background and wait for /health
#   stop     Stop the running container (keeps the image and volume)
#   restart  Restart the running container
#   logs     Follow container logs
#   test     Probe /health (and /v1/models when proxy auth is enabled)
#   status   Show compose service status
#   down     Stop and remove the container (keeps the named volume)

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
ENV_FILE="$PROJECT_ROOT/.env"
PORT_DEFAULT=8082

log() { printf '%s\n' "$*"; }
err() { printf 'error: %s\n' "$*" >&2; }
die() { err "$*"; exit 1; }

# Curated shortlist: "id|ENV_VAR|example model id|credential URL".
PROVIDERS='deepseek|DEEPSEEK_API_KEY|deepseek/deepseek-chat|https://platform.deepseek.com/api_keys
open_router|OPENROUTER_API_KEY|open_router/deepseek/deepseek-chat-v3.1|https://openrouter.ai/keys
groq|GROQ_API_KEY|groq/llama-3.3-70b-versatile|https://console.groq.com/keys
cerebras|CEREBRAS_API_KEY|cerebras/qwen-3-coder-480b|https://cloud.cerebras.ai
mistral|MISTRAL_API_KEY|mistral/mistral-large-latest|https://console.mistral.ai/
together|TOGETHER_API_KEY|together/deepseek-ai/DeepSeek-V3|https://api.together.ai/settings/api-keys
zai|ZAI_API_KEY|zai/glm-4.6|https://z.ai/manage-apikey/apikey-list
nvidia_nim|NVIDIA_NIM_API_KEY|nvidia_nim/nvidia/nemotron-3-super-120b-a12b|https://build.nvidia.com/settings/api-keys'

detect_compose() {
    if docker compose version >/dev/null 2>&1; then
        COMPOSE='docker compose'
    elif command -v docker-compose >/dev/null 2>&1; then
        COMPOSE='docker-compose'
    else
        die "Docker Compose not found. Install Docker Desktop or the compose plugin."
    fi
}

compose() {
    # shellcheck disable=SC2086
    ( cd "$PROJECT_ROOT" && $COMPOSE "$@" )
}

require_env_file() {
    [ -f "$ENV_FILE" ] || die "No .env found. Run: $0 setup"
}

env_port() {
    if [ -f "$ENV_FILE" ] && grep -q '^PORT=' "$ENV_FILE"; then
        grep '^PORT=' "$ENV_FILE" | head -n1 | cut -d= -f2- | tr -d '"'
    else
        printf '%s' "$PORT_DEFAULT"
    fi
}

prompt() {
    # prompt VARNAME "question" ["default"]
    _p_var=$1
    _p_q=$2
    _p_def=${3:-}
    if [ -n "$_p_def" ]; then
        printf '%s [%s]: ' "$_p_q" "$_p_def" >&2
    else
        printf '%s: ' "$_p_q" >&2
    fi
    IFS= read -r _p_ans || _p_ans=''
    [ -n "$_p_ans" ] || _p_ans=$_p_def
    eval "$_p_var=\$_p_ans"
}

gen_token() {
    if command -v python3 >/dev/null 2>&1; then
        python3 -c 'import secrets; print(secrets.token_urlsafe(24))'
    elif [ -r /dev/urandom ]; then
        LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | dd bs=1 count=32 2>/dev/null
    else
        printf 'freecc-%s' "$(date +%s)"
    fi
}

cmd_setup() {
    force=0
    [ "${1:-}" = "--force" ] && force=1
    if [ -f "$ENV_FILE" ] && [ "$force" -eq 0 ]; then
        die ".env already exists. Re-run with: $0 setup --force"
    fi

    log "Select a provider:"
    i=0
    printf '%s\n' "$PROVIDERS" | while IFS='|' read -r id _ model _; do
        i=$((i + 1))
        printf '  %d) %-12s  e.g. %s\n' "$i" "$id" "$model"
    done
    log "  9) other (enter provider id / env var / model manually)"

    prompt choice "Choice" "1"

    env_var=''
    model=''
    provider_id=''
    if [ "$choice" = "9" ] || [ "$choice" = "other" ]; then
        prompt provider_id "Provider id (see README 'Choose A Provider')"
        prompt env_var "API key env var name (e.g. OPENROUTER_API_KEY)"
        prompt model "Model id (format: <provider_id>/<model>)"
    else
        line=$(printf '%s\n' "$PROVIDERS" | sed -n "${choice}p")
        [ -n "$line" ] || die "Invalid choice: $choice"
        provider_id=$(printf '%s' "$line" | cut -d'|' -f1)
        env_var=$(printf '%s' "$line" | cut -d'|' -f2)
        default_model=$(printf '%s' "$line" | cut -d'|' -f3)
        cred_url=$(printf '%s' "$line" | cut -d'|' -f4)
        log "Get a key: $cred_url"
        prompt model "Model id" "$default_model"
    fi

    [ -n "$env_var" ] || die "API key env var name is required"
    [ -n "$model" ] || die "Model id is required"
    prompt api_key "$env_var value"
    [ -n "$api_key" ] || die "API key is required"

    prompt auth_choice "Require a bearer token from coding clients? (y/N)" "N"
    proxy_auth_enabled=false
    proxy_auth_token=freecc
    case "$auth_choice" in
        y | Y | yes | YES)
            proxy_auth_enabled=true
            proxy_auth_token=$(gen_token)
            ;;
    esac

    prompt port "Host port to publish" "$PORT_DEFAULT"

    umask 077
    {
        printf '# Generated by scripts/docker-deploy.sh setup on %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
        printf '# Provider: %s\n\n' "$provider_id"
        printf '%s=%s\n' "$env_var" "$api_key"
        printf 'MODEL=%s\n\n' "$model"
        printf 'PROXY_AUTH_ENABLED=%s\n' "$proxy_auth_enabled"
        printf 'ANTHROPIC_AUTH_TOKEN=%s\n\n' "$proxy_auth_token"
        printf 'HOST=0.0.0.0\n'
        printf 'PORT=%s\n' "$port"
        printf 'FCC_OPEN_BROWSER=false\n'
    } >"$ENV_FILE"

    log ""
    log "Wrote $ENV_FILE"
    if [ "$proxy_auth_enabled" = true ]; then
        log "Proxy auth token: $proxy_auth_token"
    fi
    log "Next: $0 build && $0 start"
}

cmd_build() {
    detect_compose
    require_env_file
    compose build "$@"
}

cmd_start() {
    detect_compose
    require_env_file
    compose up -d "$@"

    port=$(env_port)
    log "Waiting for http://localhost:$port/health ..."
    n=0
    while [ "$n" -lt 30 ]; do
        if curl -fsS "http://localhost:$port/health" >/dev/null 2>&1; then
            log "FCC is healthy at http://localhost:$port"
            return 0
        fi
        n=$((n + 1))
        sleep 1
    done
    err "Server did not report healthy within 30s. Check: $0 logs"
    return 1
}

cmd_stop() {
    detect_compose
    compose stop "$@"
}

cmd_restart() {
    detect_compose
    compose restart "$@"
}

cmd_logs() {
    detect_compose
    compose logs -f "$@"
}

cmd_status() {
    detect_compose
    compose ps "$@"
}

cmd_down() {
    detect_compose
    compose down "$@"
}

cmd_test() {
    require_env_file
    port=$(env_port)
    base="http://localhost:$port"

    log "GET $base/health"
    curl -fsS "$base/health" || { err "health check failed"; return 1; }
    log ""

    if grep -q '^PROXY_AUTH_ENABLED=true' "$ENV_FILE"; then
        token=$(grep '^ANTHROPIC_AUTH_TOKEN=' "$ENV_FILE" | head -n1 | cut -d= -f2-)
        log "GET $base/v1/models (authenticated)"
        curl -fsS -H "Authorization: Bearer $token" "$base/v1/models" \
            || { err "models check failed"; return 1; }
        log ""
    fi
    log "OK"
}

usage() {
    sed -n '4,15p' "$0" | sed 's/^# \{0,1\}//'
}

main() {
    [ "$#" -ge 1 ] || { usage; exit 2; }
    subcmd=$1
    shift
    case "$subcmd" in
        setup) cmd_setup "$@" ;;
        build) cmd_build "$@" ;;
        start) cmd_start "$@" ;;
        stop) cmd_stop "$@" ;;
        restart) cmd_restart "$@" ;;
        logs) cmd_logs "$@" ;;
        test) cmd_test "$@" ;;
        status) cmd_status "$@" ;;
        down) cmd_down "$@" ;;
        -h | --help | help) usage ;;
        *) err "unknown subcommand: $subcmd"; usage; exit 2 ;;
    esac
}

main "$@"
